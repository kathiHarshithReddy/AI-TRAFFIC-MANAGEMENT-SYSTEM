function transliterateWord(word: string, lang: IndicLanguage): string {
  const lower = word.toLowerCase();
  const curated = CURATED_PHRASE_GLOSSARY[lower]?.[lang];
  if (curated) return curated;

  // Preserve pure numbers or route codes like 500D, 335E, NH-48, 1–9
  if (/^\d+([a-zA-Z]{1,2})?$/.test(word) || /^[A-Z]{2,4}-\d+/.test(word)) {
    return word;
  }

  const tbl = SCRIPT_TABLES[lang];
  let out = '';
  let i = 0;

  while (i < lower.length) {
    // Check consonant match
    const cKey = CONSONANT_KEYS.find((k) => lower.startsWith(k, i));
    if (cKey) {
      let glyph = tbl.consonants[cKey];
      i += cKey.length;

      // Handle doubled consonant (e.g., 'll' in Mallathahalli, 'tt' in Gottigere)
      if (
        cKey.length === 1 &&
        i < lower.length &&
        lower[i] === cKey &&
        cKey !== 'h'
      ) {
        glyph = glyph + tbl.virama + tbl.consonants[cKey];
        i += 1;
      }

      // Check following vowel
      const vKey = VOWEL_KEYS.find((k) => lower.startsWith(k, i));
      if (vKey) {
        out += glyph + tbl.vowelsMatra[vKey];
        i += vKey.length;
      } else if (i < lower.length && /[a-z]/.test(lower[i])) {
        // Consonant cluster
        if (
          cKey === 'n' &&
          (lower[i] === 'k' ||
            lower[i] === 'g' ||
            lower[i] === 'd' ||
            lower[i] === 't' ||
            lower[i] === 'c' ||
            lower[i] === 'j')
        ) {
          out += tbl.anusvara;
        } else {
          out += glyph + tbl.virama;
        }
      } else {
        // Word-final consonant: natural implicit schwa or virama depending on script
        if (lang === 'ta' || lang === 'ml') {
          out += glyph + tbl.virama;
        } else {
          out += glyph;
        }
      }
      continue;
    }

    // Check independent vowel at start or hiatus
    const vKey = VOWEL_KEYS.find((k) => lower.startsWith(k, i));
    if (vKey) {
      out += tbl.vowelsIndep[vKey];
      i += vKey.length;
      continue;
    }

    // Fallback character passthrough
    out += word[i] ?? '';
    i += 1;
  }

  return out;
}

export function localizeMetroLineName(
  line: MetroLine,
  lang: AppLanguage
): string {
  return METRO_LINE_TRANSLATIONS[line][lang];
}

/**
 * Translates/transliterates any Bengaluru locality, station, junction, or landmark
 * cleanly into the target script while preserving route codes and numbers.
 */
export function localizeBengaluruPlaceName(
  text: string,
  lang: AppLanguage
): string {
  if (lang === 'en' || !text) return text;

  // Replace explicit Metro line names first
  let working = text
    .replace(/\bPurple Line\b/gi, METRO_LINE_TRANSLATIONS.Purple[lang])
    .replace(/\bGreen Line\b/gi, METRO_LINE_TRANSLATIONS.Green[lang])
    .replace(/\bYellow Line\b/gi, METRO_LINE_TRANSLATIONS.Yellow[lang])
    .replace(/\bPink Line\b/gi, METRO_LINE_TRANSLATIONS.Pink[lang]);

  // Transliterate English word tokens while preserving punctuation, arrows, numbers, and Indic chars
  return working.replace(/[A-Za-z]+(?:'[A-Za-z]+)?/g, (token) =>
    transliterateWord(token, lang)
  );
}
